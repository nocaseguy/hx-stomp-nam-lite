"""Tap LED Color: Global Settings > Displays picks the TAP footswitch's colour, for its ring as it blinks the tempo and for its
switch icon and label on the Home screen, from the stock footswitch palette (src/m4/tap_color.s). External MIDI clock keeps the
stock blue ring. Rainbow moves the ring a small step round the colour wheel at each beat, Random lights it a random colour; both with a White label. BPM's Color Tempo reads tap_now."""
from features import Setting

FLAG = 'HX_TAP_COLOR'
MENU = 'Displays'
ORDER = 10                          # before BPM, which reads tap_now
MODULE, NOW = 'src/m4/tap_color.s', 'tap_now'
SETTINGS = (     # a label's last line shows on top, as BPM's 'Size\nFont' reads Font over Size
    Setting('color', b'Color\nTap LED', (b'Red', b'DkOrange', b'LtOrange', b'Yellow', b'Green', b'Teal', b'Blue', b'Violet',
                                         b'Pink', b'White', b'Rainbow', b'Random')),
)

# The stock palette, by value: the LED driver's lit colours (0x28dd8030, 0x00BBGGRR) and the block categories' label colours
# (0x28e2815c, 0xRRGGBB), White their gray
LEDS = (0x0300ff, 0x002dff, 0x00afd0, 0x00ff84, 0x00ff06, 0x80ff00, 0xff3200, 0xff0032, 0x2800ff, 0xceff6b)
TEXTS = (0xff0000, 0xff5a18, 0xf5911e, 0xead82f, 0x43ff40, 0x3cceb5, 0x0097e4, 0xb049db, 0xf12f91, 0xb1b1b1)
# Rainbow: Red, Dk Orange, Yellow, Green, Blue, Violet, each blended into the next (Violet into Red) in SHADES steps
RAINBOW_ANCHORS, SHADES = (0, 1, 3, 4, 6, 7), 7

LED_COLOUR = 0x28db81fc             # (led, 0xBBGGRR): an LED's lit colour
# The stock beat's two calls that light the TAP ring red, each after loading the red from its literal; the external clock's blue
# calls beside them stay stock.
TAP_RED, TAP_RED_LITS = 0x28e280b0, (0x28d9bee0, 0x28d9bf84)
LED_CALLS = (0x28d9bea8, 0x28d9bf6e)                # the beat's turn, then 0x28d9bf2c's: a tap, the LED refresh
LED_HANDLERS = ('tap_led', 'tap_led_again')
# The Home label builder's TAP case (0x28dc7e80, its case at 0x28dc7f7c): both label lines red, then Icon_SwitchRed (0x78).
SET_COLOR, SET_IMAGE = 0x28e24a28, 0x28e24c18
TEXT_CALLS = ((0x28dc7fca, 0x28dc7fc6), (0x28dc7fd4, 0x28dc7fce))  # (the call, its mov.w r1,#0xff0000)
RED_TEXT = bytes.fromhex('4ff47f01')
ICON_CALL, ICON_MOV, ICON_RED = 0x28dc8010, 0x28dc800c, bytes.fromhex('7821')    # movs r1,#0x78
HOME_PAINT_LIT, HOME_PAINT = 0x28d96e28, 0x28dc8d39                  # the Home view's paint function, as registered


def blend(a, b, k, n):
    """Colour a moved k/n of the way to b, a byte at a time, rounded."""
    return sum(((a >> s & 0xff) * (n - k) + (b >> s & 0xff) * k + n // 2) // n << s for s in (0, 8, 16))


def rainbow():
    """[(ring colour, label colour)] of Rainbow's steps, from Red round to just before Red again."""
    anchors = [(LEDS[i], TEXTS[i]) for i in RAINBOW_ANCHORS]
    return [(blend(a[0], b[0], k, SHADES), blend(a[1], b[1], k, SHADES))
            for a, b in zip(anchors, anchors[1:] + anchors[:1]) for k in range(SHADES)]


def rainbow_inc():
    steps = rainbow()
    words = lambda col: '\n'.join('    .word ' + ', '.join(f'{c[col]:#08x}' for c in steps[i:i + 7]) for i in range(0, len(steps), 7))
    return (f'@ rainbow.inc - generated by tools/features/tap_color.py\n.equ STEPS, {len(steps)}\n'
            f'.macro RAINBOW_LEDS\n{words(0)}\n.endm\n.macro RAINBOW_TEXTS\n{words(1)}\n.endm\n')


def apply(p):
    m = p.module(MODULE, inc={'rainbow.inc': rainbow_inc()})
    for lit in TAP_RED_LITS:
        if p.u32(lit) != TAP_RED:
            raise SystemExit(f'patch-menu: the stock beat does not load its red at {lit:#x}')
    for site, handler in zip(LED_CALLS, LED_HANDLERS):
        p.own_call(site, LED_COLOUR, f'the stock beat lighting the TAP ring at {site:#x}', m[handler])
    for site, mov in TEXT_CALLS:
        p.expect(mov, RED_TEXT, 'the TAP label colour')
        p.own_call(site, SET_COLOR, f'the TAP label colour at {site:#x}', m['tap_text'])
    p.expect(ICON_MOV, ICON_RED, 'the TAP switch icon')
    p.own_call(ICON_CALL, SET_IMAGE, 'the TAP switch icon', m['tap_icon'])
    p.chain_ptr(HOME_PAINT_LIT, HOME_PAINT, before=m['tap_paint'])
